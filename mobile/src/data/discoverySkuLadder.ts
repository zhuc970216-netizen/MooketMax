import {normalizeFactoryNoOrNull} from '../utils/factoryNo';

export type DiscoveryLadderTier = 'T0' | 'T1' | 'T2' | 'T3' | 'T4';

export type DiscoveryLadderEntry = {
  factoryNo: string;
  note?: string;
};

export type DiscoveryLadderGroup = {
  country: '巴西';
  canonicalProductName: string;
  displayName: string;
  aliases: string[];
  tiers: Record<DiscoveryLadderTier, DiscoveryLadderEntry[]>;
};

const TIER_ORDER: DiscoveryLadderTier[] = ['T0', 'T1', 'T2', 'T3', 'T4'];

function buildEntry(factoryNo: string, note?: string): DiscoveryLadderEntry {
  return {
    factoryNo: normalizeFactoryNoOrNull(factoryNo) ?? factoryNo,
    note,
  };
}

function buildEntries(factoryNos: string[]) {
  return factoryNos.map(factoryNo => buildEntry(factoryNo));
}

