const normalizedAliasMatchers = DISCOVERY_SKU_LADDER.map(group => ({
  group,
  aliases: group.aliases.map(alias => normalizeProductName(alias)),
}));

function normalizeProductName(value: string) {
  return value.trim().toLowerCase().replace(/[\s·•\-_/]/g, '');
}

function normalizeCountry(value?: string | null) {
  return value?.trim() ?? '';
}

export function getDiscoveryLadderTiers() {
  return TIER_ORDER.slice();
}

export function getDiscoveryLadderGroup(
  country?: string | null,
  productName?: string | null,
) {
  if (normalizeCountry(country) !== '巴西') {
    return null;
  }
  const normalizedProductName = normalizeProductName(productName ?? '');
  if (!normalizedProductName) {
    return null;
  }

  return (
    normalizedAliasMatchers.find(({aliases}) =>
      aliases.some(alias => normalizedProductName.includes(alias)),
    )?.group ?? null
  );
}

export function canonicalizeDiscoveryProductName(
  country?: string | null,
  productName?: string | null,
) {
  return getDiscoveryLadderGroup(country, productName)?.canonicalProductName ?? null;
}

export function getDiscoveryLadderTierInfo(
  country?: string | null,
  productName?: string | null,
  factoryNo?: string | null,
) {
  const group = getDiscoveryLadderGroup(country, productName);
  const normalizedFactoryNo = normalizeFactoryNoOrNull(factoryNo);
  if (!group || !normalizedFactoryNo) {
    return null;
  }

  for (const tier of TIER_ORDER) {
    const entry = group.tiers[tier].find(item => item.factoryNo === normalizedFactoryNo);
    if (entry) {
      return {group, tier, entry};
    }
  }

  return null;
}

export function getDiscoveryTierIndex(tier: DiscoveryLadderTier) {
  return TIER_ORDER.indexOf(tier);
}
